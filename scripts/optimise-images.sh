#!/usr/bin/env bash
# Makes responsive AVIF and WebP copies of every JPG in public/images, and writes
# src/data/images.ts (intrinsic size and available widths per image) for the <Picture> component.
# Run it after adding or replacing a photo. Needs macOS `sips` (AVIF, resizing) and `cwebp` (brew install webp).
set -euo pipefail
cd "$(dirname "$0")/.."
SRC=public/images
OUT=public/images/r
WIDTHS=(480 750 1000)
mkdir -p "$OUT"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

manifest="// Generated by scripts/optimise-images.sh. Do not edit by hand.
export interface ImageInfo {
  width: number
  height: number
  /** Widths with AVIF and WebP copies in /images/r/<name>-<width>.(avif|webp). */
  widths: readonly number[]
}

export const IMAGES: Readonly<Record<string, ImageInfo>> = {
"
for jpg in "$SRC"/*.jpg; do
  name=$(basename "$jpg" .jpg)
  w=$(sips -g pixelWidth "$jpg" | awk '/pixelWidth/ {print $2}')
  h=$(sips -g pixelHeight "$jpg" | awk '/pixelHeight/ {print $2}')
  made=()
  for target in "${WIDTHS[@]}"; do
    if (( target > w )); then continue; fi
    made+=("$target")
    sips --resampleWidth "$target" "$jpg" --out "$TMP/$name-$target.jpg" >/dev/null
    cwebp -quiet -q 74 -m 6 "$TMP/$name-$target.jpg" -o "$OUT/$name-$target.webp"
    sips -s format avif -s formatOptions 55 "$TMP/$name-$target.jpg" --out "$OUT/$name-$target.avif" >/dev/null
  done
  # Narrower than the smallest target: keep one copy at its own width.
  if (( ${#made[@]} == 0 )) || (( w < 1000 && w != made[${#made[@]}-1] )); then
    made+=("$w")
    cwebp -quiet -q 74 -m 6 "$jpg" -o "$OUT/$name-$w.webp"
    sips -s format avif -s formatOptions 55 "$jpg" --out "$OUT/$name-$w.avif" >/dev/null
  fi
  list=$(IFS=,; echo "${made[*]}")
  manifest+="  '$name': { width: $w, height: $h, widths: [${list//,/, }] },
"
done
manifest+="}
"
printf '%s' "$manifest" > src/data/images.ts
echo "images: $(ls "$OUT" | wc -l | tr -d ' ') files in $OUT"
